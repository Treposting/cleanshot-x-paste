import AppKit

/// Watches the system pasteboard.
///
/// macOS has no "clipboard changed" notification, so every clipboard manager
/// (Paste, Maccy, Raycast...) polls `NSPasteboard.changeCount`, a counter that
/// increments whenever any app writes to the pasteboard.
@MainActor
final class ClipboardMonitor {
    private let store: ClipboardStore
    private var timer: Timer?
    private var lastChangeCount = 0

    /// Marker types defined at http://nspasteboard.org that password managers
    /// and other apps set to ask clipboard managers not to record an entry.
    private static let ignoredTypes: Set<String> = [
        "org.nspasteboard.ConcealedType",
        "org.nspasteboard.TransientType",
        "org.nspasteboard.AutoGeneratedType",
        "com.agilebits.onepassword",
        "com.typeit4me.clipping",
        "de.petermaurer.TransientPasteboardType",
        "Pasteboard generator type",
    ]

    init(store: ClipboardStore) {
        self.store = store
    }

    func start() {
        lastChangeCount = NSPasteboard.general.changeCount
        let timer = Timer(timeInterval: 0.5, repeats: true) { [weak self] _ in
            Task { @MainActor in self?.poll() }
        }
        timer.tolerance = 0.2
        RunLoop.main.add(timer, forMode: .common)
        self.timer = timer
    }

    func stop() {
        timer?.invalidate()
        timer = nil
    }

    /// Call after Marquee itself writes to the pasteboard (e.g. pasting a
    /// history item) so the write is not recorded as a new entry.
    func ignoreCurrentContents() {
        lastChangeCount = NSPasteboard.general.changeCount
    }

    private func poll() {
        let pb = NSPasteboard.general
        guard pb.changeCount != lastChangeCount else { return }
        lastChangeCount = pb.changeCount
        guard !Preferences.monitorPaused else { return }

        let types = pb.types ?? []
        if types.contains(where: { Self.ignoredTypes.contains($0.rawValue) }) { return }

        let app = NSWorkspace.shared.frontmostApplication

        // Priority: files > text > image. Copying text from rich apps often adds
        // an image preview too, and copying a file in Finder also adds its name as text.
        if let urls = pb.readObjects(forClasses: [NSURL.self], options: [.urlReadingFileURLsOnly: true]) as? [URL],
           !urls.isEmpty {
            store.addFiles(urls, app: app)
        } else if let text = pb.string(forType: .string), !text.isEmpty {
            store.addText(text, app: app)
        } else if let png = Self.pngData(from: pb) {
            store.addImage(pngData: png, app: app)
        }
    }

    private static func pngData(from pb: NSPasteboard) -> Data? {
        if let png = pb.data(forType: .png) { return png }
        if let tiff = pb.data(forType: .tiff), let rep = NSBitmapImageRep(data: tiff) {
            return rep.representation(using: .png, properties: [:])
        }
        return nil
    }
}
